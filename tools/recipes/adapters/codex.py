"""Per-skill agents/openai.yaml for Codex.

Holds the skill picker labels and, for user-invoked skills, the policy that
pairs with Claude's `disable-model-invocation: true`, so a skill is
user-invoked in both harnesses or in neither.
"""

from __future__ import annotations

import json

from ..config import PluginConfig
from ..skill import SKILLS_DIR, Skill
from .base import Files

HEADER = "# GENERATED by tools/recipes from SKILL.md. Edit SKILL.md, then run `make build`."


def _q(value: str) -> str:
    """A JSON string is a valid YAML double-quoted scalar."""
    return json.dumps(value, ensure_ascii=False)


class CodexSkillMetadataAdapter:
    name = "codex"

    def enabled(self, config: PluginConfig) -> bool:
        return config.targets.codex_skill_metadata

    def render(self, config: PluginConfig, skills: list[Skill]) -> Files:
        return {
            f"{SKILLS_DIR}/{skill.directory.name}/agents/openai.yaml": self._yaml(skill)
            for skill in skills
        }

    @staticmethod
    def _yaml(skill: Skill) -> str:
        lines = [
            HEADER,
            "interface:",
            f"  display_name: {_q(skill.display_name)}",
            f"  short_description: {_q(skill.short_description)}",
        ]
        if skill.user_invoked:
            lines += ["policy:", "  allow_implicit_invocation: false"]
        return "\n".join(lines) + "\n"
